test('DESIGN-06/07/11 timer and phase, the tabs of each mode, and a reload resumes the same session with canvas and notes intact', async ({ page }) => {
  test.setTimeout(60_000)
  const check = guard(page)
  await begin(page)
  const tabsOf: Record<Partner, string[]> = { Solo: ['notes', 'dives'], Interviewer: ['notes', 'partner', 'dives'], 'With someone': ['notes', 'partner', 'dives'] }
  for (const partner of ['Interviewer', 'With someone', 'Solo'] as Partner[]) {
    await page.clock.resume()
    await startSession(page, partner)
    await expect(page.getByTestId('session-phase')).toHaveText('Drawing')
    // 45:00, or 45:01 when the one-second display tick is a moment older than the start (a polling artifact, see design-session.spec D-5)
    await expect(page.getByTestId('session-timer')).toHaveText(/^45:0[01]$/)
    await page.clock.runFor(3000)
    await expect(page.getByTestId('session-timer')).toHaveText(/^44:5[5-9]$/)
    const tabs = await page.getByRole('tab').evaluateAll(els => els.map(e => e.getAttribute('data-testid')!.replace('session-tab-', '')))
    expect(tabs).toEqual(tabsOf[partner])
    await expect(page.getByTestId('session-tab-notes')).toHaveAttribute('aria-selected', 'true')
    for (const t of tabsOf[partner]) await expect(page.getByTestId(`session-tabpanel-${t}`)).toHaveCount(1)
    await expect(page.getByTestId('session-tabpanel-notes')).toBeVisible()
    await expect(page.getByTestId('session-tabpanel-dives')).toBeHidden()
    await addKind(page, 'gateway')
    await openNotes(page)
    await page.getByTestId('notes-field-open').fill(`kept in ${partner}`)
    await page.getByTestId('kit-add-note').click()
    await page.getByTestId('kit-note-text-note-1').fill('a sticky')
    await expect.poll(async () => (await liveRow(page)).canvas.notes?.[0]?.text).toBe('a sticky') // the writes have landed
    await resumeAndGo(page, () => page.reload())
    await expect(page.getByTestId('session-phase')).toHaveText('Drawing')
    await expect(page.getByTestId('session-setup')).toHaveCount(0)
    await expect(page.getByTestId('kit-count')).toHaveText('1 nodes · 0 links')
    await expect(page.getByTestId('notes-field-open')).toHaveValue(`kept in ${partner}`)
    await expect(page.getByTestId('kit-note-text-note-1')).toHaveValue('a sticky')
    expect((await page.getByRole('tab').count())).toBe(tabsOf[partner].length)
    expect((await liveRow(page)).mode).toBe(MODE_OF[partner])
    if (partner === 'Interviewer') await expect(msgs(page)).toHaveCount(1) // the opener is not asked again on a reload
    await discard(page)
  }
  check()
})

