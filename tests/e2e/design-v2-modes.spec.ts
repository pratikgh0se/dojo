import { addKind, aiLogRows, begin, designRows, drawS1, endDrawing, fillClose, guard, liveRow, openPartner, pick, resumeAndGo, RL, RL_DIVES, RL_TITLE, scoreS1, startSession, type Partner, openNotes } from './design-helpers'

// Design session v2, setup and the three modes (DESIGN-01 to 08, 11, 43 to 54, 68, 71, 73, 80) on the fake provider.
const msgs = (page: Page) => page.getByTestId('session-msg')
const chat = (page: Page) => page.getByTestId('session-chat-input')
/** What a learner may read in an AI message: the text element, never the label (DESIGN-45). */
const aiTexts = (page: Page) => page.locator('[data-testid="session-msg"][data-from="ai"] [data-testid="session-msg-text"]').allTextContents()
async function answer(page: Page, text: string) {
  const n = await msgs(page).count()
  await chat(page).fill(text)
  await page.getByTestId('session-send').click()
  await expect(msgs(page)).toHaveCount(n + 2)
}
/** The fake provider's delay is a timer set a few async hops after the click, and the test clock is frozen: advance it until the reply is in. */
const letTimersRun = (page: Page, list: Locator, count: number) =>
  expect.poll(async () => { await page.clock.runFor(250); return list.count() }, { timeout: 10_000 }).toBe(count)
/** Run an action that asks the helper and wait for the round trip itself: the loader appears (the fake delay is set) and then goes (the frozen clock is advanced by hand). */
const roundTrip = async (page: Page, act: () => Promise<unknown>, loader = 'ai-loader') => {
  await page.evaluate(() => localStorage.setItem('dojo-ai-fake-delay-ms', '600'))
  await act()
  await expect(page.getByTestId(loader)).toBeVisible()
  await expect.poll(async () => { await page.clock.runFor(250); return page.getByTestId(loader).count() }, { timeout: 10_000 }).toBe(0)
  await page.evaluate(() => localStorage.removeItem('dojo-ai-fake-delay-ms'))
}
const ticketsJson = async (page: Page) => JSON.stringify(await idbAll(page, 'tickets'))
const MODE_OF: Record<Partner, string> = { Solo: 'solo', Interviewer: 'ai-partner', 'With someone': 'human-partner' }
const discard = async (page: Page) => {
  await page.getByTestId('session-discard').click()
  await page.getByTestId('session-discard-confirm').click()
  await expect(page.getByTestId('session-setup')).toBeVisible()
}

