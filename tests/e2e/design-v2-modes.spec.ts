test('DESIGN-46/47/48/49/52/68/69/70 hint, twelve answers, the topics in order with a challenge, one question a turn, the grade and its log', async ({ page }) => {
  test.setTimeout(150_000)
  const check = guard(page)
  await begin(page)
  await startSession(page, 'Interviewer')
  await openPartner(page)
  await expect(msgs(page)).toHaveCount(1)
  // dive progression (aria-current on session-dive-<n>) across the answers: none before the design turns, then 1, 2, 2, 3, 4, 4, 4
  const activeDive = [0, 0, 0, 0, 0, 0, 1, 2, 2, 3, 4, 4, 4]
  const expectDive = async (answers: number) => {
    for (let n = 1; n <= 4; n++) {
      const el = page.getByTestId(`session-dive-${n}`)
      if (activeDive[answers] === n) await expect(el, `dive ${n} after ${answers} answers`).toHaveAttribute('aria-current', 'step')
      else await expect(el, `dive ${n} after ${answers} answers`).not.toHaveAttribute('aria-current', /.+/)
    }
  }
  await expectDive(0)
  // DESIGN-49 the Hint: disabled while the reply is pending; one new AI message, kind hint, same topic as the question it sharpens
  await page.evaluate(() => localStorage.setItem('dojo-ai-fake-delay-ms', '600'))
  await page.getByTestId('session-hint').click()
  await expect(page.getByTestId('session-hint')).toBeDisabled()
  await expect(page.getByTestId('ai-loader')).toBeVisible()
  await letTimersRun(page, msgs(page), 2)
  await expect(page.getByTestId('ai-loader')).toHaveCount(0)
  await expect(msgs(page).nth(1)).toHaveAttribute('data-kind', 'hint')
  await expect(msgs(page).nth(1)).toHaveAttribute('data-topic', 'requirements')
  await expect(page.getByTestId('session-hint')).toContainText('2 left')
  await page.evaluate(() => localStorage.removeItem('dojo-ai-fake-delay-ms'))
  // DESIGN-50: send disabled and a loader while the reply is pending
  await page.evaluate(() => localStorage.setItem('dojo-ai-fake-delay-ms', '600'))
  await chat(page).fill('5M daily users')
  await page.getByTestId('session-send').click()
  await expect(msgs(page)).toHaveCount(3)
  await expect(msgs(page).nth(2)).toHaveAttribute('data-from', 'you')
  await expect(page.getByTestId('ai-loader')).toBeVisible()
  await expect(page.getByTestId('session-send')).toBeDisabled()
  await letTimersRun(page, msgs(page), 4)
  await expect(page.getByTestId('ai-loader')).toHaveCount(0)
  await page.evaluate(() => localStorage.removeItem('dojo-ai-fake-delay-ms'))
  await expectDive(1)
  // eleven more answers: twelve in all
  for (let i = 2; i <= 12; i++) {
    await answer(page, `answer ${i}`)
    await expectDive(i)
  }
  await expect(page.locator('[data-testid="session-msg"][data-from="you"]')).toHaveCount(12)
  const ai = await msgs(page).evaluateAll(els => els
    .filter(e => e.getAttribute('data-from') === 'ai')
    .map(e => ({ kind: e.getAttribute('data-kind'), topic: e.getAttribute('data-topic'), text: e.querySelector('[data-testid="session-msg-text"]')!.textContent! })))
  expect(ai).toHaveLength(14)
  // DESIGN-46: one question each, ending with it, no list markers, no answers handed over
  for (const [i, m] of ai.entries()) {
    expect(m.text.match(/\?/g), `AI message ${i + 1}: ${m.text}`).toHaveLength(1)
    expect(m.text.trimEnd().endsWith('?'), `AI message ${i + 1} ends with the question`).toBe(true)
    expect(m.text, `AI message ${i + 1} has a list marker`).not.toMatch(/^\s*([-*]|\d+\.)\s/m)
    expect(m.text, `AI message ${i + 1} hands over an answer`).not.toMatch(/you could|you should|i suggest|consider using|the answer is/i)
    expect(m.text).not.toMatch(/\binterview/i)
  }
  // DESIGN-47: the topics, challenges ignored, never go back and all four occur; DESIGN-48: a challenge within the first twelve
  const ORDER = ['requirements', 'estimates', 'design', 'tradeoffs']
  const flow = ai.filter(m => m.topic !== 'challenge').map(m => ORDER.indexOf(m.topic!))
  expect(flow.every(t => t >= 0)).toBe(true)
  expect(flow).toEqual([...flow].sort((a, b) => a - b))
  for (const t of ORDER) expect(ai.map(m => m.topic), t).toContain(t)
  expect(ai.slice(0, 12).some(m => m.topic === 'challenge')).toBe(true)
  // the hint took the topic of the question before it
  expect(ai[1]).toMatchObject({ kind: 'hint', topic: ai[0].topic })
  expect(ai.filter(m => m.kind === 'hint')).toHaveLength(1)
  await expect(page.getByTestId('session-interview-status')).toHaveText('Trade-offs · discussion')
  // to the grade: DESIGN-68
  await endDrawing(page)
  await expect(page.getByTestId('session-tabs')).toHaveCount(0)
  await fillClose(page, RL_DIVES[0])
  await expect(page.getByTestId('session-grade')).toBeVisible()
  const items = page.locator('[data-testid^="session-grade-item-"]')
  await expect(items).toHaveCount(5)
  const scores = await items.evaluateAll(els => els.map(e => e.getAttribute('data-score')!))
  for (const s of scores) expect(s).toMatch(/^\d+$/)
  const sum = scores.reduce((a, s) => a + Number(s), 0)
  await expect(page.getByTestId('session-grade-total')).toHaveText(`${sum} of 20`)
  expect(sum).toBeGreaterThanOrEqual(0)
  expect(sum).toBeLessThanOrEqual(20)
  await expect(page.getByTestId('session-rubric')).toHaveValue(String(sum))
  await expect(page.getByTestId('session-grade-inconsistencies')).toHaveCount(0) // the default grade lists no checks (DESIGN-70)
  // DESIGN-52: one interview row per AI message, one grade row, all fake
  const rows = await aiLogRows(page)
  expect(rows.filter(r => r.job === 'interview' && r.ok)).toHaveLength(ai.length)
  expect(rows.filter(r => r.job === 'grade' && r.ok)).toHaveLength(1)
  expect(rows.filter(r => r.job === 'interview' || r.job === 'grade').every(r => r.provider === 'fake')).toBe(true)
  // complete: the stored rubric is that total
  const row2 = page.getByTestId('session-tradeoff-row-2')
  await row2.getByRole('textbox', { name: 'Chose' }).fill('fail open')
  await row2.getByRole('textbox', { name: 'Over' }).fill('fail closed')
  await row2.getByRole('textbox', { name: 'Because' }).fill('limiter outage must not take the API down')
  await page.getByTestId('session-complete').click()
  await expect(page.getByTestId('session-phase')).toHaveText('Done')
  const done = await liveRow(page)
  expect(done).toMatchObject({ phase: 'done', mode: 'ai-partner', rubric: sum, rubricBy: 'model' })
  await expect(page.getByTestId('session-grade-total')).toHaveText(`${sum} of 20`)
  await expect(msgs(page)).toHaveCount(26)
  check()
})

