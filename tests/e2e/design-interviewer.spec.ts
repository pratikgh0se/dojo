import { expect, test, type Page } from '@playwright/test'
import { addKind, begin, drawS1, endDrawing, fillClose, guard, openPartner, pick, resumeAndGo, RL, RL_DIVES, startSession } from './design-helpers'

const msgs = (page: Page) => page.getByTestId('session-msg')
const aiMsgs = (page: Page) => page.locator('[data-testid="session-msg"][data-from="ai"]')
const chat = (page: Page) => page.getByTestId('session-chat-input')
async function answer(page: Page, text: string) {
  const n = await msgs(page).count()
  await chat(page).fill(text)
  await page.getByTestId('session-send').click()
  await expect(msgs(page)).toHaveCount(n + 2)
}

test('D-32/D-33 the AI partner speaks first, then one question per answer, with no last turn; D-34 no double send', async ({ page }) => {
  const check = guard(page)
  await begin(page)
  await startSession(page, 'Interviewer')
  await openPartner(page)
  await expect(msgs(page)).toHaveCount(1)
  await expect(msgs(page).first()).toHaveAttribute('data-from', 'ai')
  await expect(msgs(page).first().getByTestId('session-msg-label')).toHaveText('AI partner')
  await expect(msgs(page).first().getByTestId('session-msg-text')).toHaveText(/^\[fake:partner\].*d-ratelimit/)
  await expect(page.getByRole('log', { name: 'Conversation' })).toBeVisible()
  await expect(page.getByTestId('session-interview-status')).toHaveText('Requirements')
  await addKind(page, 'gateway')
  await expect(page.getByTestId('kit-node-gateway-1')).toBeVisible()
  await openPartner(page)

  await chat(page).fill('   ')
  await expect(page.getByTestId('session-send')).toBeDisabled()
  await chat(page).fill('QPS 10k, 1M tenants')
  await page.getByTestId('session-send').dblclick()
  await expect(msgs(page)).toHaveCount(3)
  await expect(msgs(page).nth(1)).toHaveAttribute('data-from', 'you')
  await expect(msgs(page).nth(1).getByTestId('session-msg-label')).toHaveText('You')
  await expect(msgs(page).nth(1).getByTestId('session-msg-text')).toHaveText('QPS 10k, 1M tenants')
  await expect(msgs(page).nth(2).getByTestId('session-msg-text')).toHaveText(/^\[fake:partner\].*d-ratelimit/)
  await expect(chat(page)).toHaveValue('')
  await expect(chat(page)).toBeFocused()
  await expect(page.getByTestId('session-interview-status')).toHaveText('Requirements')
  // the phase follows the number of answers: 3 -> Estimates, 5 -> a challenge turn, 6 -> Design (and the first deep dive)
  for (let i = 2; i <= 6; i++) {
    await answer(page, `answer ${i}`)
    if (i === 3) await expect(page.getByTestId('session-interview-status')).toHaveText('Estimates')
    if (i === 5) await expect(page.getByTestId('session-interview-status')).toHaveText('Estimates · discussion')
  }
  await expect(page.getByTestId('session-interview-status')).toHaveText('Design')
  await expect(page.getByTestId('session-dive-1')).toHaveAttribute('aria-current', 'step')
  // there is no last turn: the chat stays open past the table (12 answers, 13 AI messages)
  for (let i = 7; i <= 12; i++) await answer(page, `answer ${i}`)
  await expect(page.locator('[data-testid="session-msg"][data-from="you"]')).toHaveCount(12)
  await expect(aiMsgs(page)).toHaveCount(13)
  await expect(page.getByTestId('session-interview-status')).toHaveText('Trade-offs · discussion')
  await expect(chat(page)).toBeEnabled()
  await expect(chat(page)).not.toHaveAttribute('readonly', '')
  check()
})

test('D-35 conversation survives reload without re-asking; closing removes the chat (DESIGN-12)', async ({ page }) => {
  const check = guard(page)
  await begin(page)
  await startSession(page, 'Interviewer')
  await openPartner(page)
  for (const a of ['a1', 'a2', 'a3']) await answer(page, a)
  const before = await page.getByTestId('session-msg-text').allTextContents()
  await page.clock.runFor(1000)
  await resumeAndGo(page, () => page.reload())
  await expect(msgs(page)).toHaveCount(7)
  expect(await page.getByTestId('session-msg-text').allTextContents()).toEqual(before)
  await endDrawing(page)
  await expect(page.getByTestId('session-tabs')).toHaveCount(0)
  await expect(page.getByTestId('session-interviewer')).toHaveCount(0)
  await expect(page.getByTestId('session-close')).toBeVisible()
  check()
})

test('D-36 the 45-minute lock ends the drawing and the chat with it', async ({ page }) => {
  // Advancing a virtual clock 45 real minutes still processes every 1 s `useNow` tick along the
  // way; that real CPU cost runs close to Playwright's default 30 s test timeout on this machine.
  test.setTimeout(60_000)
  const check = guard(page)
  await begin(page)
  await startSession(page, 'Interviewer')
  await page.clock.runFor(45 * 60_000)
  await expect(page.getByTestId('session-phase')).toHaveText('Close')
  await expect(page.getByRole('status').filter({ hasText: 'Canvas locked at 45 minutes' })).toBeVisible()
  await expect(page.getByTestId('session-tabs')).toHaveCount(0)
  await expect(page.getByTestId('session-interviewer')).toHaveCount(0)
  check()
})

test('D-37/D-38 AI partner grade prefills the score form (data set S2), stored for the Done view', async ({ page }) => {
  const check = guard(page)
  await begin(page)
  await startSession(page, 'Interviewer')
  await drawS1(page)
  await openPartner(page)
  for (let i = 1; i <= 9; i++) await answer(page, `answer ${i}`)
  await endDrawing(page)
  await fillClose(page, RL_DIVES[0])
  const score = page.getByTestId('session-score')
  const checked = async (group: string) => {
    const radios = score.getByRole('radiogroup', { name: group, exact: true }).getByRole('radio')
    for (let v = 0; v < 3; v++) if (await radios.nth(v).isChecked()) return v
    return -1
  }
  await expect(page.getByTestId('session-grade')).toBeVisible()
  expect(await Promise.all(RL_DIVES.map(q => checked(q)))).toEqual([1, 1, 2, 1])
  expect(await Promise.all(['Load', 'Data', 'Consistency', 'Failure', 'Latency', 'Cost', 'Evolution'].map(l => checked(l)))).toEqual([2, 1, 1, 1, 1, 0, 1])
  await expect(score.getByRole('spinbutton', { name: 'Rubric (0–20)' })).toHaveValue('15')
  await expect(page.locator('[data-testid^="session-grade-item-"]')).toHaveCount(5)
  await expect(page.getByTestId('session-grade')).toContainText('One thing to study: [fake:partner] d-ratelimit')
  await pick(page, 'Cost', 1)
  await pick(page, 'Cost', 0)
  const row2 = page.getByTestId('session-tradeoff-row-2')
  await row2.getByRole('textbox', { name: 'Chose' }).fill('fail open')
  await row2.getByRole('textbox', { name: 'Over' }).fill('fail closed')
  await row2.getByRole('textbox', { name: 'Because' }).fill('limiter outage must not take the API down')
  await page.getByTestId('session-complete').click()
  await expect(page.getByTestId('session-phase')).toHaveText('Done')
  await expect(page.getByTestId('session-summary')).toContainText(/Solo · AI partner · \d+ min · rubric 15 \/ 20/)
  await expect(page.getByTestId('session-redesign')).toHaveCount(0)
  await resumeAndGo(page, () => page.reload())
  await expect(page.getByTestId('session-phase')).toHaveText('Done')
  await expect(page.getByText('Conversation', { exact: true })).toBeVisible()
  await expect(msgs(page)).toHaveCount(19)
  await expect(page).toHaveURL(new RegExp(`/designs/session/${RL}\\?session=`))
  check()
})
