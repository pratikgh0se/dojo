test('D-14 connect with the mouse; D-16 move with the mouse; D-19 delete with the mouse', async ({ page }) => {
  const check = guard(page)
  await begin(page)
  await startSession(page)
  await addKinds(page, ['gateway', 'service', 'cache', 'sql'])
  await page.getByTestId('kit-port-gateway-1').dragTo(page.getByTestId('kit-node-service-1'))
  const link = page.getByTestId('kit-link-gateway-1-service-1')
  await expect(link).toHaveAttribute('data-kind', 'sync')
  await expect(link).toHaveAccessibleName('Gateway 1 to Service 1 · sync')
  await expect(page.getByTestId('kit-count')).toHaveText('4 nodes · 1 links')
  // y kept within the canvas's own rendered height (min(70vh, 640px); 70vh of a 720px viewport is 504px).
  await page.getByTestId('kit-port-gateway-1').dragTo(page.getByTestId('kit-canvas'), { targetPosition: { x: 20, y: 400 } })
  await page.getByTestId('kit-port-gateway-1').dragTo(page.getByTestId('kit-node-gateway-1'))
  await page.getByTestId('kit-port-gateway-1').dragTo(page.getByTestId('kit-node-service-1'))
  await expect(page.getByTestId('kit-count')).toHaveText('4 nodes · 1 links')

  const cache = page.getByTestId('kit-node-cache-1')
  const [x0, y0] = [Number(await cache.getAttribute('data-x')), Number(await cache.getAttribute('data-y'))]
  const box = (await cache.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 48, box.y + box.height / 2 + 24, { steps: 4 })
  await page.mouse.up()
  await expect(cache).toHaveAttribute('data-x', String(x0 + 2))
  await expect(cache).toHaveAttribute('data-y', String(y0 + 1))

  await page.getByTestId('kit-node-gateway-1').click()
  await page.keyboard.press('Backspace')
  await expect(page.getByTestId('kit-node-gateway-1')).toHaveCount(0)
  await expect(page.getByTestId('kit-link-gateway-1-service-1')).toHaveCount(0)
  check()
})

