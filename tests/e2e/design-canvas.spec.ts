import { readFileSync } from 'node:fs'
import { expect, test, type Page } from '@playwright/test'
import { addKinds, begin, drawS1, endDrawing, guard, keyLink, RL, resumeAndGo, setKind, startSession } from './design-helpers'

const json = async (page: Page) => {
  const pre = page.getByTestId('kit-json')
  if (!(await pre.count())) await page.getByRole('button', { name: 'JSON', exact: true }).click()
  return JSON.parse((await pre.textContent()) ?? '{}')
}

test('D-12 add nodes by click; D-15, D-17 kind and rename; D-21 JSON; D-22 reload', async ({ page }) => {
  const check = guard(page)
  await begin(page)
  await startSession(page)
  await addKinds(page, ['gateway', 'service', 'cache', 'sql'])
  await expect(page.getByTestId('kit-node-gateway-1')).toHaveAccessibleName('Gateway 1 · gateway')
  // [data-node-id] excludes the "kit-node-label" text input, whose testid also matches the "kit-node-" prefix.
  const cells = await page.locator('[data-testid^="kit-node-"][data-node-id]').evaluateAll(els => els.map(e => `${(e as HTMLElement).dataset.x},${(e as HTMLElement).dataset.y}`))
  expect(new Set(cells).size).toBe(4)
  await expect(page.getByTestId('kit-count')).toHaveText('4 nodes · 0 links')
  await expect(page.getByTestId('kit-node-sql-1')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByTestId('kit-node-sql-1')).toBeFocused()

  await keyLink(page, 'gateway-1', 'service-1')
  await setKind(page, 'gateway-1', 'service-1', 'async')
  await page.getByTestId('kit-node-sql-1').click()
  await page.getByRole('textbox', { name: 'Node label' }).fill('Redis counters')
  await page.getByRole('textbox', { name: 'Node label' }).press('Enter')
  await expect(page.getByTestId('kit-node-sql-1')).toHaveAccessibleName('Redis counters · sql')
  const j = await json(page)
  expect(await page.getByTestId('kit-json').textContent()).toContain('{"from":"gateway-1","to":"service-1","kind":"async"}')
  expect(j.layout).toBe('manual')
  expect(j.nodes).toHaveLength(4)
  for (const n of j.nodes) {
    expect(Number.isInteger(n.x) && Number.isInteger(n.y)).toBe(true)
  }
  for (const l of j.links) expect(j.nodes.map((n: { id: string }) => n.id)).toEqual(expect.arrayContaining([l.from, l.to]))

  await page.getByRole('group', { name: 'View' }).getByRole('button', { name: 'Iso' }).click()
  await page.clock.runFor(1000)
  await resumeAndGo(page, () => page.reload())
  await expect(page.getByTestId('session-phase')).toHaveText('drawing')
  await expect(page.getByRole('group', { name: 'View' }).getByRole('button', { name: 'Iso' })).toHaveAttribute('aria-pressed', 'true')
  expect(await json(page)).toEqual(j)
  await expect(page.getByTestId('kit-link-gateway-1-service-1')).toHaveAttribute('data-kind', 'async')
  check()
})

test('D-18 the whole flow without a mouse', async ({ page }) => {
  const check = guard(page)
  await begin(page)
  await startSession(page)
  await page.getByRole('button', { name: 'Add browser', exact: true }).focus()
  for (let i = 0; i < 8; i++) await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('button', { name: 'Add lb', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  const lb = page.getByTestId('kit-node-lb-1')
  await expect(lb).toBeFocused()
  const x0 = Number(await lb.getAttribute('data-x'))
  const y0 = Number(await lb.getAttribute('data-y'))
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowDown')
  await expect(lb).toHaveAttribute('data-x', String(x0 + 2))
  await expect(lb).toHaveAttribute('data-y', String(y0 + 1))
  await page.getByRole('button', { name: 'Add service', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('kit-node-service-1')).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(lb).toBeFocused()
  await page.keyboard.press('l')
  await expect(page.getByTestId('kit-status')).toHaveText('Link from Lb 1: pick a target')
  await page.keyboard.press('Tab')
  await expect(page.getByTestId('kit-node-service-1')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('kit-link-lb-1-service-1')).toHaveAttribute('data-kind', 'sync')
  await expect(page.getByTestId('kit-status')).toHaveText('')
  await lb.focus()
  await page.keyboard.press('l')
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('kit-status')).toHaveText('')
  await page.getByTestId('kit-node-service-1').focus()
  await page.keyboard.press('Delete')
  await expect(page.getByTestId('kit-count')).toHaveText('1 nodes · 0 links')
  await lb.focus()
  for (const k of ['1', '2', '5', '9', 't', 'd', 's', ' ']) await page.keyboard.press(k)
  await expect(page).toHaveURL(new RegExp(`/designs/session/${RL}$`))
  await page.getByRole('textbox', { name: 'Node label' }).focus()
  await page.keyboard.press('1')
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL(new RegExp(`/designs/session/${RL}$`))
  await expect(page.getByTestId('kit-count')).toHaveText('1 nodes · 0 links')
  check()
})

