test('D-43 Export PNG downloads a real PNG named by design and day', async ({ page }) => {
  const check = guard(page)
  await begin(page)
  await startSession(page)
  await drawS1(page)
  const [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export PNG', exact: true }).click()])
  expect(dl.suggestedFilename()).toBe('d-ratelimit-2026-10-11.png')
  const bytes = readFileSync((await dl.path())!)
  expect([...bytes.subarray(0, 8)]).toEqual([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
  expect(bytes.length).toBeGreaterThan(1024)
  await endDrawing(page)
  const [again] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export PNG', exact: true }).click()])
  expect(again.suggestedFilename()).toBe('d-ratelimit-2026-10-11.png')
  check()
})
