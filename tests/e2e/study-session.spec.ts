test('UX-10: End session asks the three fields and Progress shows them', async ({ page }) => {
  await begin(page)
  const xp0 = await xp(page)
  await page.goto(CARD)
  await startSession(page, { goal: 'end log' })
  await page.getByRole('button', { name: 'End session' }).click()
  const dlg = page.getByRole('dialog', { name: 'End session' })
  for (const name of ['Done', 'Stuck on', 'Next step']) await expect(dlg.getByRole('textbox', { name })).toHaveAttribute('maxlength', '280')
  await dlg.getByRole('textbox', { name: 'Done' }).fill('the loop')
  await dlg.getByRole('textbox', { name: 'Stuck on' }).fill('queue order')
  await dlg.getByRole('textbox', { name: 'Next step' }).fill('edge cases')
  await dlg.getByRole('button', { name: 'Save' }).click()
  await expect(dlg).toBeHidden()
  await expect(page.getByTestId('session-timer')).toHaveCount(0)
  const rows = await idbAll<{ outcome: string; xpDelta: number; endLog: unknown }>(page, 'sessions')
  expect(rows).toHaveLength(1)
  expect(rows[0]).toMatchObject({ outcome: 'studied', xpDelta: 0, endLog: { done: 'the loop', stuckOn: 'queue order', nextStep: 'edge cases' } })
  await page.goto('/progress')
  await expect(page.getByTestId('screen-progress')).toHaveAttribute('data-ready', 'true')
  const item = page.locator('[data-testid^="study-session-"]')
  await expect(item).toContainText('Done: the loop')
  await expect(item).toContainText('Stuck on: queue order')
  await expect(item).toContainText('Next step: edge cases')
  await page.reload()
  await expect(page.locator('[data-testid^="study-session-"]')).toContainText('Next step: edge cases')
  expect(await xp(page)).toBe(xp0)
})

test('readability holds in every session state: plan dialog, session panel, focus mode, stuck and end dialogs', async ({ page }) => {
  await begin(page)
  const bad = async (label: string) => {
    const els = await ownTextElements(page)
    const tiny = els.filter(e => e.size < 14).map(e => `${e.tag}.${e.cls} "${e.text}" ${e.size}px`)
    const pixel = els.filter(e => /^"?Silkscreen/.test(e.family) && ![16, 24, 32, 48].includes(e.size)).map(e => `${e.tag}.${e.cls} ${e.size}px`)
    expect([label, tiny, pixel]).toEqual([label, [], []])
  }
  await page.getByRole('button', { name: 'Start session' }).click()
  await bad('plan dialog')
  await page.getByRole('radio', { name: 'Custom' }).check()
  await bad('plan dialog custom')
  await page.getByRole('dialog', { name: 'Plan this session' }).getByRole('button', { name: 'Start', exact: true }).click()
  await expect(page.getByTestId('session-timer')).toBeVisible()
  await bad('session panel')
  // ui-do D4 / ruling 10: the ladder's rung notes are Chivo 15 secondary descriptions, not reading paragraphs
  const ps = (await ownTextElements(page)).filter(e => e.tag === 'p' && e.cls !== 'rung-note')
  for (const p of ps) expect([p.cls, /^"?Chivo/.test(p.family), p.size >= 17, p.lh >= 1.5 * p.size - 0.01]).toEqual([p.cls, true, true, true])
  await page.keyboard.press('f')
  await bad('focus mode')
  await page.keyboard.press('Escape')
  await page.clock.fastForward('25:00')
  await expect(page.getByRole('dialog', { name: 'Stuck?' })).toBeVisible()
  await bad('stuck dialog')
  await page.getByRole('button', { name: "I'm fine" }).click()
  await page.getByRole('button', { name: 'End session' }).click()
  await bad('end dialog')
})

