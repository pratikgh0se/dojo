  await expect(dlg).toContainText('You were away: Resume or End?')
  await expect(dlg.getByRole('button', { name: 'Resume' })).toBeVisible()
  expect(await idbAll<{ t: string; minutes?: number }>(page, 'events').then(es => es.filter(e => e.t === 'focus').map(e => e.minutes))).toEqual([25])
