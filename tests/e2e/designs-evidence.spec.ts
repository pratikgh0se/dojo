  expect(await ev.getByTestId('wall-cell').nth(6).getAttribute('data-design')).toBe(RL)
  await expect(ev.getByText('2 of 192 answered in full')).toBeVisible()
  await expect(page.getByTestId('designs-sundays')).toHaveText('2 deep dives answered')
  const thumb = ev.getByTestId('shelf-tier-2').getByTestId('shelf-thumb')
  await expect(thumb).toHaveAccessibleName(`${RL_TITLE} · 2026-10-11 · 4 nodes`)
  await expect(ev.getByTestId('design-vocab')).toHaveText('Vocabulary · 4 of 38 kinds used')
  await resumeAndGo(page, () => page.reload())
  await expect(ev.getByTestId('lens-radar')).toHaveAccessibleName(`Lens radar · last 6: ${one} · all-time: ${one}`)
