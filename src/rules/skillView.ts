/** An area arrow is "met" when its prerequisite area has any done ticket (SKILLS-05). */
export const areaEdgeMet = (plan: PlanV2, fromAreaId: string, tickets: readonly Ticket[]): boolean =>
  tickets.some(t => !t.archived && t.status === 'done' && areaOfTicket(t) === fromAreaId)

/** Why a node is soft-locked, in words: unwritten tickets, or what is recommended first. */
export function lockedReason(node: PlanNode, plan: PlanV2, states: ReadonlyMap<string, NodeState>): string {
  if ((states.get(node.id) ?? 'locked') !== 'locked') return ''
  const phase = plan.phases.find(p => p.p === node.phase)
  if (phase && !phase.authored) return `Not open yet: tickets written before phase ${node.phase}.`
  const first = node.pre.flatMap(id => {
    const n = plan.nodes.find(x => x.id === id)
    return n && states.get(id) !== 'done' ? [n.title] : []
  })
  if (first.length === 0) return 'Tickets for this topic are not written yet.'
  const shown = first.slice(0, 2).join(' and ')
  return `Recommended first: ${shown}${first.length > 2 ? ` and ${first.length - 2} more` : ''}.`
}

export const unlocksOf = (nodeId: string, plan: PlanV2): PlanNode[] => plan.nodes.filter(n => n.pre.includes(nodeId))

/** The first ticket of a node that can be started, in queue order: `todo` or `doing`. A blocked or need-help ticket is skipped (BOARD-42), as Today skips it. */
export function nextTicketOf(nodeId: string, tickets: readonly Ticket[]): Ticket | null {
  return nodeTickets(nodeId, tickets).filter(t => t.status === 'todo' || t.status === 'doing' || t.status === 'slid').sort((a, b) => effectiveOrder(a) - effectiveOrder(b))[0] ?? null
}

/** The next item of a DSA or Design node (trees Definitions, TREE-12): the first `doing` item, else the first `todo` item, by effective order. */
export function nextItemOf(nodeId: string, tickets: readonly Ticket[]): Ticket | null {
  const mine = nodeTickets(nodeId, tickets)
  return mine.find(t => t.status === 'doing') ?? mine.find(t => t.status === 'todo') ?? null
}

/** TREE-05, TREE-09: done and all tree items of one tree: non-archived tickets whose `node` is a node of that tree's area. */
export function treeProgress(plan: PlanV2, areaId: string, tickets: readonly Ticket[]): { done: number; total: number } {
  const ids = new Set(plan.nodes.filter(n => n.area === areaId).map(n => n.id))
  const mine = tickets.filter(t => !t.archived && t.node !== undefined && ids.has(t.node))
  return { done: mine.filter(t => t.status === 'done').length, total: mine.length }
}

