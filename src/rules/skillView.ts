/** The DSA and Design trees are areas of the plan too, but they live on their own tabs (trees-and-banks.md); every other area is an AI area. */
export const TREE_AREA_IDS: readonly string[] = ['dsa', 'design']
export const isTreeArea = (areaId: string | undefined): boolean => areaId !== undefined && TREE_AREA_IDS.includes(areaId)
export const aiAreasOf = (plan: PlanV2): PlanArea[] => plan.areas.filter(a => !isTreeArea(a.id))
export const aiNodesOf = (plan: PlanV2): PlanNode[] => plan.nodes.filter(n => !isTreeArea(n.area))

/** Tokens `--sr-area-1..10` (one-based). Tree areas sit after the ten AI areas, so they get their own fixed colours instead of wrapping onto the first two. */
const TREE_AREA_COLOR: Record<string, number> = { dsa: 3, design: 8 }
export function areaColorIndex(plan: PlanV2, areaId: string): number {
  const fixed = TREE_AREA_COLOR[areaId]
  if (fixed !== undefined) return fixed
  const i = aiAreasOf(plan).findIndex(a => a.id === areaId)
  return (Math.max(0, i) % 10) + 1
}

type PreOf = (id: string) => readonly string[]

/** Longest chain of known prerequisites below each id (0 for a root). A cycle counts as a root. */
export function depthsOf(ids: readonly string[], preOf: PreOf): Map<string, number> {
  const known = new Set(ids)
  const memo = new Map<string, number>()
  const walk = (id: string, path: readonly string[]): number => {
    const hit = memo.get(id)
    if (hit !== undefined) return hit
    if (path.includes(id)) return 0
    const ps = preOf(id).filter(p => known.has(p) && p !== id)
    const d = ps.length === 0 ? 0 : 1 + Math.max(...ps.map(p => walk(p, [...path, id])))
    memo.set(id, d)
    return d
  }
  for (const id of ids) walk(id, [])
  return memo
}

/** "You need this first" arrows: one per prerequisite link between known ids, none implied. */
export function preEdges(ids: readonly string[], preOf: PreOf): [string, string][] {
  const known = new Set(ids)
  return ids.flatMap(id => preOf(id).filter(p => known.has(p) && p !== id).map((p): [string, string] => [p, id]))
}

export interface AreaTile { area: PlanArea; c: number; r: number; x: number; y: number }

export function layoutAreas(areas: readonly PlanArea[]): { tiles: AreaTile[]; edges: [string, string][]; width: number; height: number } {
  const ids = areas.map(a => a.id)
  const preOf: PreOf = id => areas.find(a => a.id === id)?.pre ?? []
  const useGrid = areas.every(a => AREA_GRID[a.id] !== undefined)
  const depth = depthsOf(ids, preOf)
  const nextRow = new Map<number, number>()
  const tiles = areas.map(area => {
    let cell: { c: number; r: number }
    if (useGrid) cell = AREA_GRID[area.id]
    else {
      const c = (depth.get(area.id) ?? 0) + 1
      const r = (nextRow.get(c) ?? 0) + 1
      nextRow.set(c, r)
      cell = { c, r }
    }
    return { area, c: cell.c, r: cell.r, x: (cell.c - 1) * AREA_GX, y: AREA_OY + (cell.r - 1) * AREA_GY }
  })
  const maxC = Math.max(1, ...tiles.map(t => t.c))
  const maxR = Math.max(1, ...tiles.map(t => t.r))
  return { tiles, edges: preEdges(ids, preOf), width: (maxC - 1) * AREA_GX + AREA_W, height: AREA_OY + (maxR - 1) * AREA_GY + AREA_H }
}

/** Line height of a 14 px node title, and the least and most lines a title box is sized for. */
export const CN_LINE = 17.5
export const CN_MIN_LINES = 2
export const CN_MAX_LINES = 8
/** Title width used when none is given: a 140 px box less the 2 px borders, 16 px left padding and 10 px right padding. */
export const CN_TEXT_W = 112
/** Average advance of a 14 px bold character in the body face, used only to size the box (the text itself wraps by the browser). */
export const CN_CHAR_W = 7.6

/** A text measurer: the pixel width of a string in the node title face. Absent where there is no canvas (tests), then an average advance is used. */
export type TextWidth = (text: string) => number

/** How many lines a title wraps to at the given text width (greedy word wrap, measured when a measurer is given). */
export function titleLines(title: string, textW = CN_TEXT_W, measure?: TextWidth): number {
  const w: TextWidth = measure ?? (t => t.length * CN_CHAR_W)
  let n = 1
  let cur = ''
  for (const word of title.split(/\s+/)) {
    const next = cur ? `${cur} ${word}` : word
    if (w(next) <= textW) { cur = next; continue }
    if (cur) n++
    // a word wider than the box breaks anywhere (overflow-wrap), one extra line per box width
    n += Math.max(0, Math.ceil(w(word) / textW) - 1)
    cur = word
  }
  return Math.min(CN_MAX_LINES, Math.max(CN_MIN_LINES, n))
}

export type EdgeStyle = 'mid' | 'acc' | 'dash'
/** Dashed into a locked node, orange where a gate has been met and the next step is open, grey otherwise. */
