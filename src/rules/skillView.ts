export type AreaState = 'open' | 'in-progress' | 'needs-area' | 'done'

export interface AreaSummary {
  area: PlanArea
  state: AreaState
  topicsDone: number
  topicsTotal: number
  /** minutes done and in all, over the area's tickets */
  progress: { done: number; total: number }
  /** the area of the ticket Today recommends */
  recommended: boolean
  /** names of the prerequisite areas that have no done or doing ticket yet */
  needs: string[]
}

/** SKILLS-03/05/06 read `ticket.area` only, the same field the data API oracle sums by. */
const areaOfTicket = (t: Ticket): string | undefined => t.area

export function areaSummaries(plan: PlanV2, tickets: readonly Ticket[], states: ReadonlyMap<string, NodeState>): AreaSummary[] {
  const live = tickets.filter(t => !t.archived)
  const started = (areaId: string) => live.some(t => areaOfTicket(t) === areaId && (t.status === 'done' || t.status === 'doing'))
  return aiAreasOf(plan).map(area => {
    const mine = live.filter(t => areaOfTicket(t) === area.id)
    const topics = topicsOf(plan, area.id)
    const needs = area.pre.flatMap(id => {
      const pre = plan.areas.find(a => a.id === id)
      return pre && !started(id) ? [pre.name] : []
    })
    // An area with no tickets is never `done` even though "all its tickets done" is vacuous: it stays open / needs-area.
    const state: AreaState =
      mine.length > 0 && mine.every(t => t.status === 'done') ? 'done'
        : started(area.id) ? 'in-progress'
          : needs.length > 0 ? 'needs-area' : 'open'
    return {
      area, state, topicsDone: topics.filter(n => states.get(n.id) === 'done').length, topicsTotal: topics.length,
      progress: areaProgress(area.id, plan, tickets as Ticket[]),
      recommended: topics.some(n => states.get(n.id) === 'next'), needs,
    }
  })
}

