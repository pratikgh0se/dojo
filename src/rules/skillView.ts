export interface Box { x: number; y: number; w: number; h: number }

/**
 * An orthogonal "you need this first" arrow from box `a` to box `b`, ending 6 px short of `b` where the arrowhead
 * square sits (`hx`, `hy` is its top-left). Same column: straight down or up. Same row: straight across, or an arch
 * over the tiles in between. Elsewhere: out of the right edge, down or up in the gutter, into the left edge.
 */
export function edgePath(a: Box, b: Box): { d: string; hx: number; hy: number } {
  const head = 6
  if (Math.abs(a.x - b.x) < 1) {
    const down = b.y > a.y
    const x = a.x + a.w / 2
    const y0 = down ? a.y + a.h : a.y
    const y1 = down ? b.y - head : b.y + b.h + head
    return { d: `M${x} ${y0} V${y1}`, hx: x - head / 2, hy: down ? y1 - head / 2 : y1 - head / 2 }
  }
  const right = b.x > a.x
  if (Math.abs(a.y - b.y) < 1) {
    const gap = right ? b.x - (a.x + a.w) : a.x - (b.x + b.w)
    if (gap > a.w) {
      // tiles lie between: arch above the row
      const top = a.y - 14
      const x0 = a.x + a.w / 2
      const x1 = b.x + b.w / 2
      return { d: `M${x0} ${a.y} V${top} H${x1} V${b.y - head}`, hx: x1 - head / 2, hy: b.y - head - head / 2 }
    }
    const y = a.y + a.h / 2
    const x0 = right ? a.x + a.w : a.x
    const x1 = right ? b.x - head : b.x + b.w + head
    return { d: `M${x0} ${y} H${x1}`, hx: x1 - head / 2, hy: y - head / 2 }
  }
  const x0 = right ? a.x + a.w : a.x
  const x1 = right ? b.x - head : b.x + b.w + head
  const mid = right ? b.x - Math.min(20, Math.max(8, (b.x - x0) / 2)) : b.x + b.w + Math.min(20, Math.max(8, (x0 - (b.x + b.w)) / 2))
  const y1 = b.y + b.h / 2
  return { d: `M${x0} ${a.y + a.h / 2} H${mid} V${y1} H${x1}`, hx: x1 - head / 2, hy: y1 - head / 2 }
}
