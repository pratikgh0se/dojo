#!/usr/bin/env node
// Bundles server/shared-entry.ts (the app's fake outputs, output validation and guardrail text)
// into server/gen/ai-shared.mjs for the Node helper. Uses the esbuild that Vite already installs.
//   node scripts/build-helper-shared.mjs          write the bundle
//   node scripts/build-helper-shared.mjs --check  exit 1 when the committed bundle is stale
import { build } from 'esbuild'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = join(APP, 'server', 'shared-entry.ts')
const OUT = join(APP, 'server', 'gen', 'ai-shared.mjs')
const BANNER = '// GENERATED by scripts/build-helper-shared.mjs from server/shared-entry.ts. Do not edit. Run: npm run helper:gen\n'

async function bundle() {
  const r = await build({
    entryPoints: [ENTRY],
    absWorkingDir: APP,
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    write: false,
    legalComments: 'none',
    logLevel: 'error',
    define: { 'import.meta.env': '{}' },
  })
  return BANNER + r.outputFiles[0].text
}

const code = await bundle()
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== code) {
    console.error('server/gen/ai-shared.mjs is stale. Run: npm run helper:gen')
    process.exit(1)
  }
} else {
  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, code)
  console.log(`wrote ${OUT}`)
}
