#!/usr/bin/env node
// Regenerates src/ui/glyphData.ts from the Still Room library's assets/icons/glyphs.json.
//   node scripts/sync-glyphs.mjs [glyphsJson]   (default ../still-room-design/assets/icons/glyphs.json)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

/** @param {{ size: number, glyphs: Record<string, { rows: string[] }> }} lib @returns {string} the TypeScript source */
export function buildGlyphData(lib) {
  if (lib.size !== 7) throw new Error(`expected 7 x 7 glyphs, got ${lib.size}`)
  const names = Object.keys(lib.glyphs).sort()
  const lines = names.map(n => {
    const rows = lib.glyphs[n].rows
    if (rows.length !== 7 || rows.some(r => !/^[.#]{7}$/.test(r))) throw new Error(`glyph ${n} is not 7 x 7`)
    return `  ${/^[a-z]+$/i.test(n) ? n : JSON.stringify(n)}: [${rows.map(r => `'${r}'`).join(', ')}],`
  })
  return [
    '// Generated by scripts/sync-glyphs.mjs from Still Room assets/icons/glyphs.json. Do not edit.',
    'export const GLYPHS = {', ...lines, '} as const', '', 'export type GlyphName = keyof typeof GLYPHS', '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = process.argv[2] ?? new URL('../../still-room-design/assets/icons/glyphs.json', import.meta.url).pathname
  const out = new URL('../src/ui/glyphData.ts', import.meta.url)
  writeFileSync(out, buildGlyphData(JSON.parse(readFileSync(src, 'utf8'))))
  console.log(`wrote ${out.pathname}`)
}
