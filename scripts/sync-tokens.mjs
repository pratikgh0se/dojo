#!/usr/bin/env node
// Regenerates src/styles/tokens.css from the Still Room library's assets/tokens.css and Dojo's overlay.
//   node scripts/sync-tokens.mjs [libraryTokensCss]   (default ../still-room-design/assets/tokens.css)
// The library values come first; Dojo's three deviations replace three of them; Dojo's additions follow.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

/** The deviations from the library (spec 3.3), by token. A sync that cannot find one of them stops. */
export const DEVIATIONS = {
  '--sr-label-danger': '#ff7070', // the library's #ff4d4d is 4.04:1 on a panel
  '--sr-text-secondary': '#b4bad0', // the library's on-tile value, used everywhere
  '--sr-chart-label': '#b4bad0', // follows text.secondary
}

/** Ten area hues: oklch L .72, C .17 (clipped to sRGB), 36 degree steps from 190, with glow (L .82) and shade (L .55). */
export const AREA_HUES = [
  ['#00bdb6', '#00e1d8', '#00837e'], ['#00b5e6', '#62d4ff', '#007da0'], ['#71a3ff', '#a4c5ff', '#3a6cce'],
  ['#b28aff', '#ccb6ff', '#7e57c1'], ['#e277d0', '#fe9dec', '#a64697'], ['#fb718c', '#ffa8b5', '#bb3f5c'],
  ['#f87d3b', '#ffae88', '#b74d00'], ['#d29a00', '#f4b93c', '#926a00'], ['#9cb100', '#bcd155', '#6c7b00'],
  ['#29c271', '#6ae097', '#00884a'],
]

function overlay() {
  const area = AREA_HUES.flatMap(([base, glow, shade], i) => [
    `--sr-area-${i + 1}: ${base};`, `--sr-area-${i + 1}-glow: ${glow};`, `--sr-area-${i + 1}-shade: ${shade};`,
  ])
  return [
    '/* Dojo overlay: additions with no library equivalent */',
    '/* Lightened tint of --sr-signal-arcane for text on a panel (the saturated value is 3.8:1 there). */',
    '--sr-signal-arcane-label: #a391fb;',
    '--sr-chart-well: #0f111c;',
    '--sr-chart-seq-orange-1: #7a4418;', '--sr-chart-seq-orange-2: #b8501a;', '--sr-chart-seq-orange-3: #ff8a2a;',
    '--sr-chart-seq-orange-4: #ffb545;', '--sr-chart-seq-orange-5: #ffd9a8;',
    '--sr-flash: #ffffff;',
    '/* Area identity: stripe, two-letter tag and meter only, never a node fill. Lanes reuse three of them. */',
    ...area,
    '--sr-lane-path: var(--sr-area-1);', '--sr-lane-dsa: var(--sr-area-5);', '--sr-lane-design: var(--sr-area-8);', '--sr-lane-career: var(--sr-area-9);',
    '/* Type scale (ux spec section 1): Silkscreen only at the four display sizes; everything read is Chivo, never under 14 px. */',
    '--type-display-s: 16px;', '--type-display-m: 24px;', '--type-display-l: 32px;', '--type-display-xl: 48px;',
    '--type-title: 22px;', '--type-body: 17px;', '--type-small: 15px;', '--type-meta: 14px;', '--type-leading: 1.55;', '--type-measure: 70ch;',
  ].map(l => `  ${l}`)
}

/** @param {string} libCss the library's assets/tokens.css @returns {string} Dojo's src/styles/tokens.css */
export function buildTokensCss(libCss) {
  const root = /:root\{\n([\s\S]*?)\n\}\n/.exec(libCss)
  const tail = libCss.slice(libCss.indexOf('/* bevel recipes */'))
  if (!root || !tail.startsWith('/* bevel recipes */')) throw new Error('unexpected library tokens.css shape')
  const version = /--sr-version:\s*"([^"]+)"/.exec(root[1])?.[1]
  if (!version) throw new Error('library tokens.css has no --sr-version')
  const left = new Set(Object.keys(DEVIATIONS))
  const body = root[1].split('\n').map(line => {
    const m = /^(\s*)(--[a-z0-9-]+):\s*[^;]+;\s*$/.exec(line)
    if (m && m[2] in DEVIATIONS) { left.delete(m[2]); return `${m[1]}${m[2]}: ${DEVIATIONS[m[2]]};` }
    return line
  })
  if (left.size > 0) throw new Error(`library tokens.css lacks ${[...left].join(', ')}`)
  return [
    `/* STILL ROOM tokens — generated by scripts/sync-tokens.mjs from assets/tokens.json v${version}. Dark only (ux spec §2): the light theme is removed. Dojo's overlay closes the :root block. */`,
    ':root{', '  color-scheme: dark;', ...body, ...overlay(), '}', tail,
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = process.argv[2] ?? new URL('../../still-room-design/assets/tokens.css', import.meta.url).pathname
  const out = new URL('../src/styles/tokens.css', import.meta.url)
  writeFileSync(out, buildTokensCss(readFileSync(src, 'utf8')))
  console.log(`wrote ${out.pathname}`)
}
